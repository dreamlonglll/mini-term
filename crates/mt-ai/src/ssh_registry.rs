fn quote_posix_single(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\"'\"'"))
}

fn quote_powershell_single(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

/// SKILL.md 里「这是 mini-term 生成的」那行标记(启动校正靠它认自己的生成物)。
const GENERATED_MARKER: &str = "<!-- generated by mini-term";

/// Claude 版 SKILL.md 的 `allowed-tools`:**只预批 `list` 与 `exec`**,每条规则与正文教的
/// 调用形式逐字一致。
///
/// Claude Code 的 Bash / PowerShell 规则按命令原文匹配(引号算在内,`*` 匹配任意文本,
/// 末尾的 ` *` 也匹配不带参数的形式),所以每条都写成正文里那个带引号的可执行文件 +
/// 子命令 + 本项目令牌:
/// - Bash / Git Bash:`'<路径>' list --project-token '<令牌>' *`;
/// - WSL:`"$(wslpath '<路径>')" list …`,外加命令替换里那条 `wslpath '<路径>'`
///   (Claude Code 会单独检查命令替换内部的命令);
/// - PowerShell:`& '<路径>' list …`(必须带调用运算符)。
///
/// upload / download 会读写任意本地文件,不预批 —— 每次照常弹审批。
///
/// 写成 YAML 列表、每项一个单引号标量(内部 `'` 双写):规则里有空格、引号、`$`、反斜杠,
/// 「空格 / 逗号分隔的一行」会被拆坏。路径或令牌里有 `*`(会变成通配)或换行(YAML
/// 断行)时整段不写 —— 宁可每次弹审批,也不放宽匹配面。
fn allowed_tools_block(binary_path: &str, project_token: &str) -> String {
    if [binary_path, project_token]
        .iter()
        .any(|value| value.contains(['*', '\n', '\r']))
    {
        return String::new();
    }
    let bash_binary = quote_posix_single(binary_path);
    let bash_token = quote_posix_single(project_token);
    let wsl_binary = format!("\"$(wslpath {bash_binary})\"");
    let powershell_binary = quote_powershell_single(binary_path);
    let powershell_token = quote_powershell_single(project_token);
    let mut rules = Vec::new();
    for sub in ["list", "exec"] {
        rules.push(format!(
            "Bash({bash_binary} {sub} --project-token {bash_token} *)"
        ));
    }
    for sub in ["list", "exec"] {
        rules.push(format!(
            "Bash({wsl_binary} {sub} --project-token {bash_token} *)"
        ));
    }
    rules.push(format!("Bash(wslpath {bash_binary})"));
    for sub in ["list", "exec"] {
        rules.push(format!(
            "PowerShell(& {powershell_binary} {sub} --project-token {powershell_token} *)"
        ));
    }
    let items: String = rules
        .iter()
        .map(|rule| format!("  - '{}'\n", rule.replace('\'', "''")))
        .collect();
    format!("allowed-tools:\n{items}")
}

/// 渲染 SKILL.md 内容。`with_allowed_tools` 区分 Claude 版(true,skill 激活
/// 期间免审批 list / exec)与 Codex 版(false,规避未知 frontmatter 字段的容忍度风险)。
///
/// 正文英文(与 MCP tool descriptions 一致,对两端 agent 触发与遵循最稳);
/// description 明确列出「远程执行 / 查日志 / 部署 / 传文件」等触发场景。
///
/// **这是用户不可见的 agent 面文案,不走 mt-i18n** —— 同一个项目可能被两个版本轮流
/// 启用,模板一改,启动校正([`reconcile_skill_files_on_startup`])会把旧模板的文件
/// 重写成新的。
fn render_skill_md(binary_path: &str, project_token: &str, with_allowed_tools: bool) -> String {
    let allowed_tools = if with_allowed_tools {
        allowed_tools_block(binary_path, project_token)
    } else {
        String::new()
    };
    let bash_binary = quote_posix_single(binary_path);
    let bash_token = quote_posix_single(project_token);
    let wsl_binary = format!("\"$(wslpath {bash_binary})\"");
    let powershell_binary = quote_powershell_single(binary_path);
    let powershell_token = quote_powershell_single(project_token);
    format!(
        r#"---
name: mini-term-ssh
description: Run commands or transfer files on remote servers over SSH using this project's saved connections (managed by mini-term). Use when the user asks to operate on a remote host — run commands, inspect logs, deploy services, upload or download files.
{allowed_tools}---

{GENERATED_MARKER}; do not edit (regenerated on enable) -->

# mini-term SSH CLI

This project has saved SSH connections managed by mini-term. Authentication is
handled internally — NEVER ask the user for passwords and NEVER use plain
`ssh` / `scp` / `sftp`.

CLI binary (quote the path, it may contain spaces):

    "{binary_path}"

All examples below already carry this project's capability token. Never replace
or omit it: the daemon rejects unknown tokens instead of exposing other projects.
Keep `--project-token` right after the subcommand, exactly as shown.

## Bash / Git Bash

List available connections:

    {bash_binary} list --project-token {bash_token} --json

Run a remote command:

    {bash_binary} exec --project-token {bash_token} [--cwd DIR] [--timeout SECS] <connection> -- <command...>

Upload / download files (they read or write local files, so they are not
pre-approved — expect a permission prompt):

    {bash_binary} upload   --project-token {bash_token} <connection> <local_path> <remote_path>
    {bash_binary} download --project-token {bash_token} <connection> <remote_path> <local_path>

## WSL (Windows interop)

    {wsl_binary} list --project-token {bash_token} --json
    {wsl_binary} exec --project-token {bash_token} [--cwd DIR] [--timeout SECS] <connection> -- <command...>
    {wsl_binary} upload   --project-token {bash_token} <connection> <local_path> <remote_path>
    {wsl_binary} download --project-token {bash_token} <connection> <remote_path> <local_path>

The CLI is a Windows program even inside WSL. For upload/download, give the
local path relative to the current directory, or convert an absolute path with
`"$(wslpath -w '/abs/path')"`. When the current directory is under `/mnt/*`, a
POSIX absolute local path such as `/tmp/x` is rejected (exit 2).

## PowerShell

PowerShell requires the call operator `&` before a quoted executable path:

    & {powershell_binary} list --project-token {powershell_token} --json
    & {powershell_binary} exec --project-token {powershell_token} [--cwd DIR] [--timeout SECS] <connection> -- <command...>
    & {powershell_binary} upload   --project-token {powershell_token} <connection> <local_path> <remote_path>
    & {powershell_binary} download --project-token {powershell_token} <connection> <remote_path> <local_path>

## Behaviour

- Remote stdout/stderr stream through; exit code = remote exit code.
- No TTY and no stdin: the remote command gets EOF on stdin immediately, so
  interactive prompts fail. Use non-interactive flags such as `sudo -n`,
  `apt-get -y`, `DEBIAN_FRONTEND=noninteractive`.
- `--cwd DIR` assumes a POSIX shell on the remote host (the command becomes
  `cd DIR && ...`). On Windows hosts, put the directory change into the command
  itself instead.
- `--timeout SECS` (default 60) covers the whole call, connecting included.
  Connecting also has its own 20 s limit: a host that cannot be reached or
  authenticated in time fails with exit 2, and raising `--timeout` won't help.
- After an authentication failure the same connection is not retried for 30 s
  (`authentication cooldown: ...`). Report the error to the user instead of
  retrying in a loop.
- Large output: append `> file.log` and read the file afterwards.

Exit codes:

- remote exit code: passed through unchanged;
- 124: timed out (`mt-ssh-cli: error: timed out ...`; "while connecting" means
  the remote command never started);
- 128+n: the remote command was killed by signal n (137 = KILL, 143 = TERM,
  255 = unrecognized signal); a `mt-ssh-cli: remote command terminated by
  signal ...` line on stderr names it;
- 2: CLI / connection / authentication error, with `mt-ssh-cli: error:` on stderr.

Do NOT base64-echo file contents through exec — use upload/download.
"#
    )
}

/// 两份 SKILL.md 的落盘路径。
fn skill_paths(project_dir: &Path) -> [(PathBuf, bool); 2] {
    [
        (
            project_dir
                .join(".claude")
                .join("skills")
                .join(SKILL_DIR_NAME)
                .join("SKILL.md"),
            true, // Claude 版含 allowed-tools
        ),
        (
            project_dir
                .join(".codex")
                .join("skills")
                .join(SKILL_DIR_NAME)
                .join("SKILL.md"),
            false,
        ),
    ]
}

/// 整文件覆盖写入两份 SKILL.md(mini-term 独占生成物,无需合并语义)。
fn write_skill_files(
    project_dir: &Path,
    binary_path: &str,
    project_token: &str,
) -> Result<(), String> {
    for (path, with_allowed_tools) in skill_paths(project_dir) {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|e| format!("创建 skill 目录失败 {}: {}", parent.display(), e))?;
        }
        let content = render_skill_md(binary_path, project_token, with_allowed_tools);
        atomic_write(&path, content.as_bytes())
            .map_err(|e| format!("写入 {} 失败: {}", path.display(), e))?;
    }
    Ok(())
}

/// 删除两份 SKILL.md 及空目录:`mini-term-ssh/` 一定删;`skills/` 若空一并删;
/// `.claude/` / `.codex/` 若因此彻底变空也顺手收掉(remove_dir 只删空目录,
/// 有其它内容时静默失败,安全)。文件不存在视为已停用(幂等)。
fn remove_skill_files(project_dir: &Path) -> Result<(), String> {
    for (path, _) in skill_paths(project_dir) {
        if path.exists() {
            std::fs::remove_file(&path)
                .map_err(|e| format!("删除 {} 失败: {}", path.display(), e))?;
        }
        // mini-term-ssh/ → skills/ → .claude|.codex/,逐级尝试删空目录。
        let mut dir = path.parent();
        for _ in 0..3 {
            let Some(d) = dir else { break };
            // 只在目录存在且为空时成功;失败(非空/不存在)即停止向上。
            if std::fs::remove_dir(d).is_err() {
                break;
            }
            dir = d.parent();
        }
    }
    Ok(())
}

