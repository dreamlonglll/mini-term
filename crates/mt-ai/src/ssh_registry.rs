    fn allowed_tool_rules(md: &str) -> Vec<String> {
        let frontmatter = md
            .strip_prefix("---\n")
            .and_then(|rest| rest.split_once("\n---\n"))
            .map(|(front, _)| front)
            .expect("frontmatter");
        let mut lines = frontmatter.lines();
        if lines.by_ref().all(|line| line != "allowed-tools:") {
            return Vec::new();
        }
        lines
            .map_while(|line| line.strip_prefix("  - "))
            .map(|item| {
                let inner = item
                    .strip_prefix('\'')
                    .and_then(|rest| rest.strip_suffix('\''))
                    .unwrap_or_else(|| panic!("每项都必须是 YAML 单引号标量: {item}"));
                assert!(
                    !inner.replace("''", "").contains('\''),
                    "单引号标量里的 ' 必须双写: {item}"
                );
                inner.replace("''", "'")
            })
            .collect()
    }

