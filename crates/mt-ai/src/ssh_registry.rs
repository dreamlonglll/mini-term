    /// A2-10:每条规则(去掉 `Tool(` 与结尾的 ` *)`)都正是正文里某条示例的开头 ——
    /// 包括 PowerShell 的 `&` 调用形式与 WSL 的 `"$(wslpath …)"`。
    #[test]
    fn allowed_tools_match_the_taught_invocations_exactly() {
        for path in [
            WIN_BIN,
            r"C:\Users\O'Brien\mt-ssh-cli.exe",
            "/opt/mini term/mt-ssh-cli",
        ] {
            let md = render_skill_md(path, "tok-1", true);
            let examples: Vec<&str> = md
                .lines()
                .filter(|line| line.starts_with("    ") && line.contains("--project-token"))
                .map(str::trim)
                .collect();
            for rule in allowed_tool_rules(&md) {
                let Some(prefix) = rule
                    .strip_prefix("Bash(")
                    .or_else(|| rule.strip_prefix("PowerShell("))
                    .and_then(|r| r.strip_suffix(" *)"))
                else {
                    // 命令替换里那一条:就是 WSL 示例里 `$(…)` 的内容
                    let inner = rule
                        .strip_prefix("Bash(")
                        .and_then(|r| r.strip_suffix(')'))
                        .expect(&rule);
                    assert!(
                        examples.iter().any(|e| e.contains(&format!("$({inner})"))),
                        "{rule}"
                    );
                    continue;
                };
                assert!(
                    examples.iter().any(|example| example.starts_with(prefix)),
                    "规则 {rule} 与正文的任何示例都对不上:\n{examples:#?}"
                );
            }
        }
    }

