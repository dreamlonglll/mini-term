/// 启动校正的输入:一个开启了「关联 SSH」、带能力令牌的**本地**项目。
#[derive(Debug, Clone)]
pub struct SkillReconcileTarget {
    pub project_dir: String,
    pub project_token: String,
}

/// 启动时校正项目里的 SKILL.md,返回重写的文件数。
///
/// 只动 [`enable`] 写过的那两份文件(Claude / Codex),且同时满足才按 enable 的写法重写:
/// - 文件存在,且是 mini-term 生成的(模板标记);
/// - 文件引用的 mt-ssh-cli 已不存在,或文件里的令牌与配置不符,或内容与当前模板的
///   输出不同(模板升级,例如收窄了 `allowed-tools`)。
///
/// 缺失的文件**不重建**(用户可能是故意删的);用户自己写的同名文件不碰;引用的是另一份
/// 仍然存在的 CLI(同机另一处安装)且内容与模板一致的不改,免得两份安装来回改写。
/// dev 实例(见 [`projection_reaches_sidecar`])整个跳过。任何失败只记日志、不返错 ——
/// 绝不影响启动;每次重写打一行日志。
///
/// **阻塞**,丢 `background_executor`。
pub fn reconcile_skill_files_on_startup(
    targets: &[SkillReconcileTarget],
    projection_dir: &Path,
) -> usize {
    if targets.is_empty() || registry_scope(projection_dir) == RegistryScope::IsolatedInstance {
        return 0;
    }
    let binary_path = match ssh_cli_binary_path() {
        Ok(path) => path,
        Err(e) => {
            eprintln!("[ssh_skill] 启动校正跳过:{e}");
            return 0;
        }
    };
    if !Path::new(&binary_path).is_file() {
        // 指向一个不存在的 CLI 只会更糟 —— 安装不完整时宁可不改。
        eprintln!("[ssh_skill] 启动校正跳过:找不到 {binary_path}");
        return 0;
    }
    reconcile_with_binary(targets, &binary_path)
}

/// 启动校正的可测核心:CLI 路径由调用方给出。
fn reconcile_with_binary(targets: &[SkillReconcileTarget], binary_path: &str) -> usize {
    let mut rewritten = 0;
    for target in targets {
        let token = target.project_token.trim();
        if token.is_empty() {
            continue;
        }
        let Ok(dir) = validate_project_dir(&target.project_dir) else {
            continue;
        };
        for (path, with_allowed_tools) in skill_paths(&dir) {
            // 不存在 / 读不了:不重建、不报错
            let Ok(content) = std::fs::read_to_string(&path) else {
                continue;
            };
            let Some(reason) = rewrite_reason(&content, token, with_allowed_tools, |binary| {
                Path::new(binary).is_file()
            }) else {
                continue;
            };
            let fresh = render_skill_md(binary_path, token, with_allowed_tools);
            match atomic_write(&path, fresh.as_bytes()) {
                Ok(()) => {
                    rewritten += 1;
                    eprintln!("[ssh_skill] 启动校正:已重写 {}({reason})", path.display());
                }
                Err(e) => eprintln!("[ssh_skill] 启动校正:重写 {} 失败: {e}", path.display()),
            }
        }
    }
    rewritten
}

/// 一份现有 SKILL.md 要不要重写、为什么;`None` = 不动。
fn rewrite_reason(
    content: &str,
    token: &str,
    with_allowed_tools: bool,
    binary_exists: impl Fn(&str) -> bool,
) -> Option<&'static str> {
    if !is_generated_skill(content) {
        return None;
    }
    let Some(binary) = referenced_binary(content) else {
        return Some("认不出的旧版生成格式");
    };
    if !binary_exists(&binary) {
        return Some("引用的 mt-ssh-cli 已不存在");
    }
    if content == render_skill_md(&binary, token, with_allowed_tools) {
        return None;
    }
    let token_arg = format!("--project-token {}", quote_posix_single(token));
    Some(if content.contains(&token_arg) {
        "模板已更新"
    } else {
        "令牌与配置不符"
    })
}

/// 是不是 mini-term 生成的 SKILL.md(frontmatter 名字 + 生成标记)。
fn is_generated_skill(content: &str) -> bool {
    content.starts_with(&format!("---\nname: {SKILL_DIR_NAME}\n"))
        && content.contains(GENERATED_MARKER)
}

/// SKILL.md 里写死的 CLI 路径:「CLI binary」那行之后第一个非空行里的双引号内容。
fn referenced_binary(content: &str) -> Option<String> {
    let mut lines = content.lines();
    lines.find(|line| line.trim_start().starts_with("CLI binary"))?;
    let quoted = lines.find(|line| !line.trim().is_empty())?.trim();
    quoted
        .strip_prefix('"')?
        .strip_suffix('"')
        .map(str::to_string)
}

