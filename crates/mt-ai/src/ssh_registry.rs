    #[test]
    fn reconcile_rewrites_files_from_an_older_template() {
        let dir = unique_test_dir("reconcile-template");
        let bin = fake_binary(&dir, "mt-ssh-cli");
        write_skill_files(&dir, &bin, "tok").unwrap();
        // 模拟旧模板:整个 CLI 放行的那一行 allowed-tools
        let current = std::fs::read_to_string(claude_md(&dir)).unwrap();
        let (head, rest) = current.split_once("allowed-tools:\n").unwrap();
        let (_, body) = rest.split_once("---\n").unwrap();
        let old = format!(
            "{head}allowed-tools: 'Bash(\"{bin}\" *), PowerShell(\"{bin}\" *)'\n---\n{body}"
        );
        std::fs::write(claude_md(&dir), &old).unwrap();

        assert_eq!(reconcile_with_binary(&[target(&dir, "tok")], &bin), 1);
        let fixed = std::fs::read_to_string(claude_md(&dir)).unwrap();
        assert_eq!(fixed, render_skill_md(&bin, "tok", true));
        // Codex 那份本来就是最新的,不动
        assert_eq!(
            std::fs::read_to_string(codex_md(&dir)).unwrap(),
            render_skill_md(&bin, "tok", false)
        );
        let _ = std::fs::remove_dir_all(&dir);
    }

