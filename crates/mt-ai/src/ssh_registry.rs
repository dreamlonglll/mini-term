/// sidecar(mt-ssh-cli)读 SSH 投影的目录:`mt_core::config_json_path()` 的所在目录
/// (它刻意不认 `MT_APP_DATA_DIR`,见 AGENTS.md「config.json 为什么还在」)。
fn sidecar_data_dir() -> Option<PathBuf> {
    mt_core::config_json_path().and_then(|path| path.parent().map(Path::to_path_buf))
}

/// 本实例写 SSH 投影(`config.json`)的目录,是不是 sidecar 读的那一个。
///
/// 不是(dev 实例设了 `MT_APP_DATA_DIR`,或进程的 APPDATA 与装机版不同)→ 本实例
/// 生成的能力令牌只存在于它自己的投影里,sidecar 永远验证不过;这时往项目里写
/// SKILL.md 只会覆盖装机版生成的那份,停用时删文件也会删掉装机版的 —— 注册器的
/// 一切副作用都该跳过(见 [`enable`] / [`disable`] / [`reconcile_skill_files_on_startup`])。
pub fn projection_reaches_sidecar(projection_dir: &Path) -> bool {
    projection_reaches(projection_dir, sidecar_data_dir().as_deref())
}

/// [`projection_reaches_sidecar`] 的可测核心。sidecar 连数据目录都定位不到时按「不是」算。
fn projection_reaches(projection_dir: &Path, sidecar_dir: Option<&Path>) -> bool {
    sidecar_dir.is_some_and(|sidecar| same_dir(projection_dir, sidecar))
}

/// 两个目录是否同一个:存在的就 canonicalize(消解 8.3 短名、符号链接 / junction),
/// 再剥 `\\?\` 前缀;Windows / macOS 按大小写不敏感、`\` `/` 等价、忽略尾随分隔符比较。
fn same_dir(a: &Path, b: &Path) -> bool {
    fn key(path: &Path) -> String {
        let resolved = std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf());
        let text = resolved.to_string_lossy().into_owned();
        let text = mt_core::path_key::strip_verbatim_prefix(&text).into_owned();
        if cfg!(any(windows, target_os = "macos")) {
            mt_core::path_key::windows_eq_key(&text)
        } else {
            mt_core::path_key::trim_trailing_separators(&text).to_string()
        }
    }
    key(a) == key(b)
}

/// 注册器这一次该不该碰磁盘。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum RegistryScope {
    /// 本实例写的投影就是 sidecar 读的那份:照常生成 / 删除 SKILL.md 等。
    Live,
    /// 投影写在别处(dev 实例):只把关联存进本实例配置,注册器一个文件都不碰。
    IsolatedInstance,
}

fn registry_scope(projection_dir: &Path) -> RegistryScope {
    if projection_reaches_sidecar(projection_dir) {
        RegistryScope::Live
    } else {
        eprintln!(
            "[ssh_skill] 本实例的配置目录 {} 不是 mt-ssh-cli 读取的目录 {}:跳过 SKILL.md / \
             .gitignore / Claude、Codex 配置的一切改动",
            projection_dir.display(),
            sidecar_data_dir()
                .map(|dir| dir.display().to_string())
                .unwrap_or_else(|| "<无法定位>".to_string())
        );
        RegistryScope::IsolatedInstance
    }
}

/// [`enable`] 的返回值。调用方必须把 `project_token` 持久化进对应项目配置
/// (`ProjectConfig::ssh_cli_token`),daemon 才能把令牌解析回项目范围。
#[derive(Debug, Clone)]
pub struct EnableResult {
    /// 面向日志的结果说明(中文,不走 mt-i18n;界面提示由调用方按档拼)。
    pub message: String,
    pub project_token: String,
    /// dev 实例隔离:注册器的副作用全部跳过,只解析了令牌(见
    /// [`projection_reaches_sidecar`])。调用方据此在界面上补一句说明。
    pub registry_skipped: bool,
}

/// [`disable`] 的返回值。
#[derive(Debug, Clone)]
pub struct DisableResult {
    /// 面向日志的结果说明(中文,不走 mt-i18n)。
    pub message: String,
    /// 同 [`EnableResult::registry_skipped`]。
    pub registry_skipped: bool,
}

/// 复用已有非空令牌;存量项目没有令牌时生成新的 UUID v4 能力令牌。
fn resolve_project_token(existing: Option<&str>) -> String {
    existing
        .map(|token| token.trim().to_string())
        .filter(|token| !token.is_empty())
        .unwrap_or_else(|| uuid::Uuid::new_v4().to_string())
}

/// 为指定项目启用 SSH 工具(CLI + Skill)。
///
/// `project_dir` 为项目目录绝对路径;已有 `project_token` 会稳定复用,存量项目
/// 缺失时生成新的能力令牌并写死进 SKILL.md。成功后该项目里新启动的
/// Claude Code / Codex 会话即可通过 skill 调用 SSH CLI(已运行的会话需重启)。
///
/// `projection_dir` 是本实例写 `config.json` 投影的目录:它不是 sidecar 读的那个
/// (dev 实例)时只解析令牌、不碰任何文件,结果里 `registry_skipped = true`。
///
/// **阻塞**,丢 `background_executor`。
pub fn enable(
    project_dir: &str,
    project_token: Option<&str>,
    projection_dir: &Path,
) -> Result<EnableResult, String> {
    enable_with_scope(project_dir, project_token, registry_scope(projection_dir))
}

fn enable_with_scope(
    project_dir: &str,
    project_token: Option<&str>,
    scope: RegistryScope,
) -> Result<EnableResult, String> {
    let dir = validate_project_dir(project_dir)?;
    let project_token = resolve_project_token(project_token);
    if scope == RegistryScope::IsolatedInstance {
        return Ok(EnableResult {
            message: "开发实例:关联只保存进本实例配置,未生成 SKILL.md".to_string(),
            project_token,
            registry_skipped: true,
        });
    }
    let binary_path = ssh_cli_binary_path()?;

    // 核心写入:任何一步失败都直接返回错误(可读中文)。
    write_skill_files(&dir, &binary_path, &project_token)?;
    trust_project_in_codex(&dir)?;
    // 存量项目自动摘除旧 MCP 注册(新项目本就没有,天然幂等)。
    cleanup_legacy_mcp(&dir)?;

    // .gitignore 追加属于附带优化,失败不致命:记 stderr 并在结果里提示。
    let gitignore_note = match append_gitignore_entries(&dir) {
        Ok(()) => String::new(),
        Err(e) => {
            eprintln!("[ssh_skill] 追加 .gitignore 失败(不影响启用): {}", e);
            "（.gitignore 未能自动更新，建议手动忽略两个 skills/mini-term-ssh/ 目录）".to_string()
        }
    };

    Ok(EnableResult {
        message: format!(
            "已为该项目启用 SSH 工具：已生成 Claude / Codex 两份 SKILL.md。{}",
            gitignore_note
        ),
        project_token,
        registry_skipped: false,
    })
}

/// 为指定项目停用 SSH 工具。
///
/// 删除本功能生成的 SKILL.md 与空目录,并兜底清理历史遗留的 MCP 注册;
/// Codex 项目信任与 `.gitignore` 条目保留(无害,且无法可靠区分是否本功能所加)。
/// `projection_dir` 的口径同 [`enable`]:dev 实例什么都不删(删的会是装机版的文件)。
///
/// **阻塞**,丢 `background_executor`。
pub fn disable(project_dir: &str, projection_dir: &Path) -> Result<DisableResult, String> {
    disable_with_scope(project_dir, registry_scope(projection_dir))
}

fn disable_with_scope(project_dir: &str, scope: RegistryScope) -> Result<DisableResult, String> {
    let dir = validate_project_dir(project_dir)?;
    if scope == RegistryScope::IsolatedInstance {
        return Ok(DisableResult {
            message: "开发实例:关联只从本实例配置里移除,未删除任何 SKILL.md".to_string(),
            registry_skipped: true,
        });
    }

    remove_skill_files(&dir)?;
    cleanup_legacy_mcp(&dir)?;

    Ok(DisableResult {
        message: "已为该项目停用 SSH 工具：已删除生成的 SKILL.md 并清理历史 MCP 注册。".to_string(),
        registry_skipped: false,
    })
}

