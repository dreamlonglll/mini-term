    /// 造一个「CLI 二进制」占位文件,返回路径。
    fn fake_binary(dir: &Path, name: &str) -> String {
        let path = dir.join(name);
        std::fs::write(&path, b"").unwrap();
        path.to_string_lossy().into_owned()
    }

    fn target(dir: &Path, token: &str) -> SkillReconcileTarget {
        SkillReconcileTarget {
            project_dir: dir.to_string_lossy().into_owned(),
            project_token: token.into(),
        }
    }

    fn claude_md(dir: &Path) -> PathBuf {
        skill_paths(dir)[0].0.clone()
    }

    fn codex_md(dir: &Path) -> PathBuf {
        skill_paths(dir)[1].0.clone()
    }

