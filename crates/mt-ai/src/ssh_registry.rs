    #[test]
    fn projection_dir_comparison_is_normalized() {
        let dir = unique_test_dir("same-dir");
        let other = unique_test_dir("other-dir");
        assert!(projection_reaches(&dir, Some(&dir)));
        // 尾随分隔符、`.` 段都不算差异
        let trailing = PathBuf::from(format!("{}{}", dir.display(), std::path::MAIN_SEPARATOR));
        assert!(projection_reaches(&trailing, Some(&dir)));
        assert!(projection_reaches(&dir.join("."), Some(&dir)));
        #[cfg(windows)]
        {
            let upper = PathBuf::from(dir.to_string_lossy().to_uppercase());
            assert!(
                projection_reaches(&upper, Some(&dir)),
                "Windows 上大小写不算差异"
            );
        }
        assert!(!projection_reaches(&other, Some(&dir)));
        // sidecar 连数据目录都定位不到:按「不是同一个」算(不写注定验证不过的 SKILL.md)
        assert!(!projection_reaches(&dir, None));
        let _ = std::fs::remove_dir_all(&dir);
        let _ = std::fs::remove_dir_all(&other);
    }

