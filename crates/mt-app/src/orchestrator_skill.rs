    use super::*;
    use std::path::PathBuf;

    fn unique_test_dir(label: &str) -> PathBuf {
        let ts = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let dir = std::env::temp_dir().join(format!("mt-orch-skill-test-{label}-{ts}"));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    const WIN_BIN: &str = r"C:\Program Files\mini term\mt-agent-cli.exe";

    fn claude_path(dir: &Path) -> PathBuf {
        skill_paths(dir, SKILL_DIR_NAME)[0].0.clone()
    }

    fn codex_path(dir: &Path) -> PathBuf {
        skill_paths(dir, SKILL_DIR_NAME)[1].0.clone()
    }

    // ─── 源文件的形状 ───

    /// 仓内源文件必须渲染得出来 —— 标记被删、frontmatter 被改坏都在这里红。
    #[test]
    fn 仓内源文件渲染得出来() {
        let md = render_skill_md(WIN_BIN, true).expect("源文件形状被改坏了");
        assert!(md.starts_with("---\nname: mini-term-orchestrator\n"), "got:\n{md}");
        // 目录名与 frontmatter 的 name 必须一致,Claude Code 按目录名找 skill
        assert!(md.contains(&format!("name: {SKILL_DIR_NAME}\n")));
        assert!(md.contains(GENERATED_MARKER));
        // 标记本身不进生成物
        assert!(!md.contains(CLI_SECTION_START));
        assert!(!md.contains(CLI_SECTION_END));
        // 源文件里那个举例路径不该留下来,换成真路径
        assert!(!md.contains("E:\\Program Files\\Mini-Term"), "got:\n{md}");
        assert!(md.contains(&format!("    \"{WIN_BIN}\"")));
        // 正文其余部分原样保留(抽几句礼仪铁律钉一下)
        assert!(md.contains("Never answer for a human"));
        assert!(md.contains("Do not `send` immediately after `start-session`"));
        // 推送模型(ADR 0004):汇报自己来,以及认出汇报的那个标记
        assert!(md.contains("Results are pushed to you"));
        assert!(md.contains("[mini-term]"));
    }

    #[test]
    fn claude_版带_allowed_tools_codex_版不带() {
        let claude = render_skill_md(WIN_BIN, true).unwrap();
        let codex = render_skill_md(WIN_BIN, false).unwrap();
        assert!(claude.contains(&format!(
            "allowed-tools: 'Bash(\"{WIN_BIN}\" *), PowerShell(\"{WIN_BIN}\" *)'\n---\n"
        )));
        assert!(!codex.contains("allowed-tools"));
        // 除了这一行,两版一字不差
        assert_eq!(
            claude.replace(
                &format!("allowed-tools: 'Bash(\"{WIN_BIN}\" *), PowerShell(\"{WIN_BIN}\" *)'\n"),
                ""
            ),
            codex
        );
    }

    #[test]
    fn 各_shell_的调用写法都在() {
        let md = render_from(SKILL_SOURCE, WIN_BIN, true, true).unwrap();
        assert!(md.contains(r#"    'C:\Program Files\mini term\mt-agent-cli.exe' <command> ...    # Bash"#));
        assert!(md.contains(r#"wslpath 'C:\Program Files\mini term\mt-agent-cli.exe'"#));
        assert!(md.contains(r#"    & 'C:\Program Files\mini term\mt-agent-cli.exe' <command> ...    # PowerShell"#));
        // 非 Windows 宿主没有 WSL 那一行
        let md = render_from(SKILL_SOURCE, "/opt/mini-term/mt-agent-cli", true, false).unwrap();
        assert!(!md.contains("wslpath"));
        assert!(md.contains("    '/opt/mini-term/mt-agent-cli' <command> ..."));
    }

    #[test]
    fn 路径里的撇号按各家规则转义() {
        let md = render_from(SKILL_SOURCE, r"C:\Users\O'Brien\mt-agent-cli.exe", true, true).unwrap();
        // YAML 单引号标量:双写
        assert!(md.contains(r#"Bash("C:\Users\O''Brien\mt-agent-cli.exe" *)"#), "got:\n{md}");
        // POSIX 单引号:'"'"'
        assert!(md.contains(r#"wslpath 'C:\Users\O'"'"'Brien\mt-agent-cli.exe'"#));
        // PowerShell 单引号:双写
        assert!(md.contains(r#"& 'C:\Users\O''Brien\mt-agent-cli.exe' <command>"#));
        // 正文(引号之外)保留原始撇号
        assert!(md.contains(r#"    "C:\Users\O'Brien\mt-agent-cli.exe""#));
    }

    #[test]
    fn 源文件缺标记时拒绝渲染() {
        let no_start = SKILL_SOURCE.replace(CLI_SECTION_START, "");
        assert!(render_from(&no_start, WIN_BIN, true, true).is_err());
        let no_end = SKILL_SOURCE.replace(CLI_SECTION_END, "");
        assert!(render_from(&no_end, WIN_BIN, true, true).is_err());
        let no_frontmatter = SKILL_SOURCE.trim_start_matches("---\n").to_string();
        assert!(render_from(&no_frontmatter, WIN_BIN, true, true).is_err());
    }

