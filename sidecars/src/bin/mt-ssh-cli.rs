//! mt-ssh-cli —— mini-term 的 SSH 命令行 sidecar(agent 经 Bash 直接调用)。
//!
//! 对标 mt-ssh-mcp 的四个工具,但走原生 CLI 契约:远程 stdout/stderr 原样流出、
//! 退出码透传、超时 124、CLI 自身错误 2 + stderr `mt-ssh-cli: error:` 前缀。
//! 业务(连接查找/池编排/审计/护栏)全部在 `mt_sidecars::ssh_service`。
//!
//! 执行路径(spec §2):**优先连 daemon**(全机单例持全局 SshPool,同一连接
//! 二次调用免 SSH 握手)——daemon 不在则自动 detached 拉起、带退避重连(拉起细节见
//! `mt_sidecars::daemon_spawn`);daemon 比 CLI 旧(app 升级后旧 daemon 残留)自动踢旧
//! 拉新,比 CLI 新则直接用(协议不同时不踢、降级);端点被非当前用户的进程占着时不连、
//! 不拉起;彻底连不上则降级为进程内 one-shot(建池 → 执行 → drain),stderr 记一行降级
//! 提示。对 agent 无感知差异。
//!
//! 退出码契约(spec §1):
//! - exec 正常:透传远程退出码;
//! - exec 远端以信号终止:`128 + 信号号`(HUP 1 … TERM 15,认不出的信号 255),stderr 补一行
//!   `mt-ssh-cli: remote command terminated by signal SIG…`(不带 `error:`,那是远端的结局);
//! - exec 远端既没报退出码也没报信号 → 2 + stderr 前缀;
//! - exec 超时:124(对齐 GNU timeout)+ stderr `mt-ssh-cli: error: timed out after <N>s`。
//!   `--timeout` 管整个请求(含建连);时限在连接阶段就用完时同样 124,stderr 说明是连接
//!   阶段、远程命令没有启动;
//! - 服务端拒绝 exec、连接/认证/传输失败、用法错误、daemon 不可达:2 + stderr 前缀,
//!   绝不含密码;
//! - list / upload / download 成功:0。
//!
//! exec 不转发 stdin:请求发出后立刻给远端 EOF,读 stdin 的命令马上读到 EOF。

