type DaemonReader = tokio::io::BufReader<tokio::io::ReadHalf<Box<dyn ipc::IpcStream>>>;
type DaemonWriter = tokio::io::WriteHalf<Box<dyn ipc::IpcStream>>;

/// 读一帧(单行);EOF / 解码失败返回 Err(String)。
async fn read_server_frame(reader: &mut DaemonReader) -> Result<ServerFrame, String> {
    use tokio::io::AsyncBufReadExt;
    let mut line = String::new();
    let n = reader
        .read_line(&mut line)
        .await
        .map_err(|e| format!("daemon connection read failed: {e}"))?;
    if n == 0 {
        return Err("daemon closed the connection".into());
    }
    ipc::decode_frame(&line)
}

/// 写请求帧。
async fn write_request(writer: &mut DaemonWriter, req: &Request) -> Result<(), String> {
    use tokio::io::AsyncWriteExt;
    let line = ipc::encode_frame(req)?;
    writer
        .write_all(line.as_bytes())
        .await
        .map_err(|e| format!("daemon connection write failed: {e}"))?;
    writer
        .flush()
        .await
        .map_err(|e| format!("daemon connection flush failed: {e}"))
}

/// 连接 daemon;连不上则 detached 拉起自身 `daemon` 并带退避重连。
async fn connect_or_spawn(ep: &str) -> Result<Box<dyn ipc::IpcStream>, DaemonUnavailable> {
    let spawned = match ipc::connect(ep).await {
        Ok(stream) => return Ok(stream),
        // 别的用户占着端点:不连、也不拉起(拉起也绑不上),直接降级。
        Err(ConnectError::Untrusted(reason)) => return Err(DaemonUnavailable::Untrusted(reason)),
        // 端点在、只是所有实例都忙(高并发瞬间,或 daemon 正在优雅退出、已不再监听):
        // 拉起新 daemon 也绑不上,只做退避重连。
        Err(e) if e.is_busy() => false,
        Err(ConnectError::Unreachable(_)) => {
            daemon_spawn::spawn_daemon_detached()?;
            true
        }
    };
    for delay in SPAWN_RETRY_DELAYS_MS {
        tokio::time::sleep(Duration::from_millis(*delay)).await;
        // 多个 CLI 并发首调:端点绑定互斥保证恰好一个 daemon 存活,
        // 抢输的实例静默退出,这里重试连接即收敛。
        match ipc::connect(ep).await {
            Ok(stream) => return Ok(stream),
            Err(ConnectError::Untrusted(reason)) => {
                return Err(DaemonUnavailable::Untrusted(reason));
            }
            Err(ConnectError::Unreachable(_)) => {}
        }
    }
    Err(DaemonUnavailable::Unreachable(if spawned {
        "daemon did not become reachable after spawning".into()
    } else {
        "daemon endpoint stayed busy (the daemon may be shutting down)".into()
    }))
}

/// v1 hello 没有 `protocolVersion`；新 CLI 将缺失字段识别为 legacy v1，
/// 才能按旧协议发送 shutdown，把旧 daemon 正常收尸。
fn peer_protocol_version(hello_protocol_version: Option<u32>) -> u32 {
    hello_protocol_version.unwrap_or(ipc::LEGACY_PROTOCOL_VERSION)
}

/// 建立一条通过版本握手的 daemon 会话(hello 已消费)。
///
/// 规则见 [`handshake_decision`]:daemon 更旧(app 升级后旧 daemon 残留)→ 发 shutdown
/// 踢掉 → 等端点释放 → 重新自拉起新版,最多两轮;daemon 更新但协议不同 → 不踢,
/// 返回 [`DaemonUnavailable::NewerIncompatible`](caller 走降级)。
///
/// ⚠️ 0.4.10 及更早的 daemon 收到 shutdown 立即退出,它手上的在途请求会被硬切断;
/// 0.4.11 起的 daemon 收到后先停止接新连接、等在途请求做完(上限 60s)再退出。
async fn open_daemon_session(ep: &str) -> Result<(DaemonReader, DaemonWriter), DaemonUnavailable> {
    let own_version = env!("CARGO_PKG_VERSION");
    let mut last_err = String::new();
    for _cycle in 0..2 {
        let stream = connect_or_spawn(ep).await?;
        let (r, w) = tokio::io::split(stream);
        let mut reader = tokio::io::BufReader::new(r);
        let mut writer = w;

        let hello = tokio::time::timeout(HELLO_TIMEOUT, read_server_frame(&mut reader))
            .await
            .map_err(|_| "daemon did not send hello in time".to_string())??;
        let (version, hello_protocol_version) = match hello {
            ServerFrame::Hello {
                version,
                protocol_version,
                ..
            } => (version, protocol_version),
            other => return Err(format!("unexpected first frame from daemon: {other:?}").into()),
        };
        let peer_protocol = peer_protocol_version(hello_protocol_version);
        match handshake_decision(&version, hello_protocol_version, own_version) {
            HandshakeDecision::Use => return Ok((reader, writer)),
            HandshakeDecision::FallBack => {
                return Err(DaemonUnavailable::NewerIncompatible {
                    version,
                    protocol: peer_protocol,
                });
            }
            HandshakeDecision::Replace => {}
        }

        // 旧 daemon 残留：按对端协议版本请求优雅退出（v1 hello 缺字段时用 v1），
        // 等它放掉端点后再拉起当前版本。
        eprintln!(
            "[mt-ssh-cli] daemon {version} (protocol v{peer_protocol}) is older than \
             {own_version} (protocol v{}), restarting daemon",
            ipc::PROTOCOL_VERSION
        );
        let shutdown = Request {
            v: peer_protocol,
            op: Some(Op::Shutdown),
            ..Default::default()
        };
        if write_request(&mut writer, &shutdown).await.is_ok() {
            // 等 ack / 连接关闭,任何结果都继续。
            let _ =
                tokio::time::timeout(Duration::from_secs(3), read_server_frame(&mut reader)).await;
        }
        drop(reader);
        drop(writer);
        // 等端点真正释放:旧版 daemon 退出前要 drain 池;0.4.11 起的 daemon 一收到
        // shutdown 就不再监听,这里很快就连不上了(它在后台把在途请求做完再退出)。
        for _ in 0..20 {
            tokio::time::sleep(Duration::from_millis(100)).await;
            if ipc::connect(ep).await.is_err() {
                break;
            }
        }
        last_err =
            format!("old daemon {version}/protocol-v{peer_protocol} still holding the endpoint");
    }
    Err(DaemonUnavailable::Unreachable(if last_err.is_empty() {
        "daemon version handshake failed".into()
    } else {
        last_err
    }))
}

/// 经 daemon 执行一个业务计划。`Err` = daemon 路径不可用(caller 降级 one-shot);
/// `Ok(code)` = 请求已被 daemon 受理并出了终帧(不再降级 —— 业务错误原样透传)。
async fn run_via_daemon(plan: &Plan) -> Result<i32, DaemonUnavailable> {
    let ep = endpoint();
    let (mut reader, mut writer) = open_daemon_session(&ep).await?;
    write_request(&mut writer, &plan.req).await?;

    loop {
        // 请求已受理后帧读取不再设短超时:请求级超时由 daemon 强制执行,
        // 终帧一定会来(daemon 崩了则读到 EOF 报错)。
        let frame = match read_server_frame(&mut reader).await {
            Ok(f) => f,
            // 已受理的请求中途断连:不能盲目重跑(exec 可能有副作用),
            // 按 CLI 错误收尾而非降级。
            Err(e) => return Ok(fail(&format!("connection to daemon lost mid-request: {e}"))),
        };
        match frame {
            ServerFrame::Stdout { data_b64 } => match ipc::b64_decode(&data_b64) {
                Ok(data) => {
                    let _ = std::io::stdout()
                        .write_all(&data)
                        .and_then(|_| std::io::stdout().flush());
                }
                Err(e) => return Ok(fail(&e)),
            },
            ServerFrame::Stderr { data_b64 } => match ipc::b64_decode(&data_b64) {
                Ok(data) => {
                    let _ = std::io::stderr()
                        .write_all(&data)
                        .and_then(|_| std::io::stderr().flush());
                }
                Err(e) => return Ok(fail(&e)),
            },
            ServerFrame::Error { message } => return Ok(fail(&message)),
            ServerFrame::Result {
                exit_code,
                timed_out,
                not_started,
                bytes,
                connections,
                ..
            } => {
                let code = match plan.req.op {
                    Some(Op::List) => {
                        let views = connections.unwrap_or_default();
                        print_connections(&views, plan.json)
                    }
                    Some(Op::Exec) => {
                        // 信号说明 daemon 已作为 stderr 帧送达,这里不再重复(signal: None)。
                        let outcome = ssh_service::ExecOutcome {
                            exit_code,
                            timed_out: timed_out.unwrap_or(false),
                            not_started: not_started.unwrap_or(false),
                            signal: None,
                        };
                        finish_exec(
                            &outcome,
                            plan.req.timeout_secs,
                            plan.req.connection.as_deref().unwrap_or(""),
                        )
                    }
                    Some(op @ (Op::Upload | Op::Download)) => {
                        let direction = op.transfer_direction().expect("transfer op");
                        match bytes {
                            Some(n) => {
                                print_transfer_summary(
                                    direction,
                                    n,
                                    plan.req.local_path.as_deref().unwrap_or(""),
                                    plan.req.remote_path.as_deref().unwrap_or(""),
                                );
                                0
                            }
                            None => fail("daemon result missing byte count"),
                        }
                    }
                    _ => fail("unexpected result frame for this operation"),
                };
                return Ok(code);
            }
            // 迟到的 hello(不应出现)忽略。
            ServerFrame::Hello { .. } => {}
        }
    }
}

