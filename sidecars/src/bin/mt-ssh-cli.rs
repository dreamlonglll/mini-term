        let order = |a: &str, b: &str| compare_versions(&version(a), &version(b));
        assert_eq!(order("0.4.10", "0.4.11"), Ordering::Less);
        // 数值比较,不是字典序。
        assert_eq!(order("0.4.9", "0.4.10"), Ordering::Less);
