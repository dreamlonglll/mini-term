/// 业务子命令归一化后的执行计划。
struct Plan {
    req: Request,
    /// list 的 `--json` 开关(仅 list 用)。
    json: bool,
}

impl Plan {
    fn new(op: Op) -> Self {
        Self {
            req: Request {
                v: ipc::PROTOCOL_VERSION,
                op: Some(op),
                ..Default::default()
            },
            json: false,
        }
    }

    /// upload / download 的计划。本地路径在这里(调用现场)绝对化;`Err` = 用法错误。
    fn transfer(
        op: Op,
        project_token: String,
        timeout: Option<u64>,
        connection: String,
        local_path: &str,
        remote_path: String,
    ) -> Result<Self, String> {
        let mut plan = Self::new(op);
        plan.req.project_token = Some(project_token);
        plan.req.connection = Some(connection);
        plan.req.local_path = Some(absolutize_local_path(local_path)?);
        plan.req.remote_path = Some(remote_path);
        plan.req.timeout_secs = timeout;
        Ok(plan)
    }
}

